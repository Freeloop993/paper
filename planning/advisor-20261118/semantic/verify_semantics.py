"""Offline reproducibility checks for the design-semantics workstream (Python 3.11+).
Only IDs, aggregate counts and status flags are written. Private source text stays local.
"""
import argparse
import collections
import hashlib
import json
import os
from pathlib import Path
import socket
import subprocess
import sys
import tempfile


def read_json(path):
    return json.loads(path.read_text(encoding="utf-8-sig"))


def read_lines(path):
    with path.open(encoding="utf-8-sig") as stream:
        return [json.loads(line) for line in stream if line.strip()]


def digest(value):
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def public_checks(data):
    cards = data["cards"]
    by_id = {card["id"]: card for card in cards}
    # PR75 searches these six fields, excluding 'state'.
    keys = ("id", "quote", "object", "category", "limits", "relation")
    # Each task/state is a design-brief field already specified by the designer.
    # No numeric default or parameter update is generated by retrieval.
    probes = [
        ("日常航拍", "未明确", "机身小巧便携", "clarify_state"),
        ("日常航拍", "折叠", "折叠后能放进背包", "folded_storage"),
        ("日常航拍", "携带", "口袋装得下吗", "pocket_fit"),
        ("日常航拍", "加装配件", "安装护罩后显大", "accessory_outline"),
        ("日常航拍", "展开顶视", "展开顶视视觉紧凑", "unfolded_compact"),
        ("农业植保", "展开顶视", "机身小巧便携", "unsupported_scope"),
        ("日常航拍", "未明确", "陌生需求词", "no_match"),
    ]
    results = []
    for task, state, query, expected in probes:
        literal = [c["id"] for c in cards if query.lower() in " ".join(c[k] for k in keys).lower()]
        # Constrain the candidate pool before looking up bilingual design concepts.
        mode, hits = "no_match", []
        if task != "日常航拍":
            mode = "unsupported_scope"
        elif state == "折叠" and any(s in query for s in ("背包", "袋", "收纳")):
            mode = "folded_storage"
            hits = [c for c in cards if c["state"] == "折叠" and "fold" in c["quote"].lower()]
        elif state == "携带" and "口袋" in query:
            mode = "pocket_fit"
            hits = [c for c in cards if "pocket" in c["quote"].lower() and c["category"] == "使用情境"]
            source_keys = {c["source_key"] for c in hits}
            hits = [c for c in cards if c["source_key"] in source_keys]
        elif state == "加装配件" and any(s in query for s in ("护罩", "保护罩", "配件")):
            mode = "accessory_outline"
            hits = [c for c in cards if "护" in c["quote"] and any(s in c["quote"] for s in ("显得挺大", "大了一圈"))]
        elif state == "展开顶视" and "紧凑" in query:
            mode = "unfolded_compact"
            hits = [c for c in cards if c["state"] == "展开" and "紧凑" in c["quote"]]
        elif state == "未明确" and any(s in query for s in ("小巧", "紧凑", "便携")):
            mode = "clarify_state"
            hits = [c for c in cards if c["state"] == "未明确" and query in c["quote"]]
        assert mode == expected
        ids = [c["id"] for c in hits]
        results.append({"task": task, "state": state, "query": query, "pr75_literal_ids": literal,
                        "rule_route": mode, "rule_ids": ids,
                        "distinct_sources": len({c["source_key"] for c in hits}), "automatic_parameter_writes": []})
    assert by_id["E003"]["source_key"] == by_id["E004"]["source_key"]
    return {"cards": len(cards), "unique_sources": len({c["source_key"] for c in cards}), "probes": results}


def private_checks(base, public):
    root = base / "补充调研_2026-10-09"
    local_cards = read_json(next(root.glob("63-*/04-*.json")))["cards"]
    pool = {r["source_key"]: r for r in read_json(next(root.glob("63-*/01-*.json")))["records"]}
    records = {r["record_id"]: r for r in read_lines(next(root.glob("02-*.jsonl")))}
    ledger = read_json(next(root.glob("64-*/06-*.json")))["records"]
    usage = {r["text_id"]: r for r in read_json(next(root.glob("62-*/11-*.json")))["records"]}
    labels = {r["group_id"]: r["label"] for r in read_json(next(root.glob("62-*/10-*.json")))["groups"]}
    retained = [r for r in ledger if r["decision_code"] == "A"]
    theme = collections.Counter(labels[group] for r in retained for group in set(usage[r["text_id"]]["group_ids"]))
    guard_groups = {"护罩构型与桨叶表达", "防护安心感知"}
    guard_union = sum(any(labels[g] in guard_groups for g in usage[r["text_id"]]["group_ids"]) for r in retained)
    by_id = {r["id"]: r for r in public["cards"]}
    for c in local_cards:
        p = pool[c["source_key"]]
        a = by_id[c["evidence_id"]]
        assert a["quote"] == c["quote_original"] and a["quote"] in p["body"]
        assert digest(p["body"]) == c["source_body_sha256"]
        assert a["source_key"] == "S-" + digest(c["source_key"])[:12]
    # Identify primary evidence cells without outputting the private contents.
    import openpyxl
    raw = base / "原始数据"
    workbooks = sorted(p for p in raw.rglob("*.xlsx") if "评论" in str(p) and not p.name.startswith("~$"))
    probes = [c for c in local_cards if c["evidence_id"] in {"E001", "E008"}]
    matches = collections.Counter()
    total = 0
    for book in workbooks:
        w = openpyxl.load_workbook(book, read_only=True, data_only=True)
        try:
            rows = iter(w.active.values)
            next(rows)
            for row in rows:
                if not any(v is not None and v != "" for v in row):
                    continue
                total += 1
                for c in probes:
                    for v in row:
                        if isinstance(v, str) and c["quote_original"] in v:
                            matches[c["evidence_id"]] += 1
        finally:
            w.close()
    for c in probes:
        orig = pool[c["source_key"]]["original_record_ids"]
        assert any(c["quote_original"] in records[i]["text"] for i in orig)
        assert matches[c["evidence_id"]] == 1
    return {"source_workbooks": len(workbooks), "nonempty_rows": total, "raw_cell_occurrences": dict(matches),
            "private_pool_to_public_cards_matched": len(local_cards), "merged": len(records), "unique_texts": len(ledger),
            "in_consumer_scope": sum("Q" in r["scopes"] for r in ledger), "retained": len(retained),
            "retained_in_Q": sum("Q" in r["scopes"] for r in retained),
            "public_cards_by_dataset": dict(collections.Counter(c["dataset"] for c in local_cards)),
            "guard_or_protection_union": guard_union, "theme_counts_multilabel": dict(theme.most_common())}


def runtime_checks(frontend, public):
    def run_node(script, *args, cwd=frontend):
        r = subprocess.run(["node", str(frontend / "scripts" / script), *map(str, args)], cwd=cwd,
                           encoding="utf-8", capture_output=True)
        return {"code": r.returncode, "summary": r.stdout.strip().splitlines()[-1] if r.stdout.strip() else "no stdout"}

    saved = frontend / "review/20261118-round3/exports"
    with tempfile.TemporaryDirectory() as tmp:
        git_root = frontend.parents[1]
        fixtures = Path(tmp) / "exports"
        for config in sorted(saved.glob("*/drone-config-*.json")):
            for source in (config, config.parent / read_json(config)["files"]["prompt"]):
                ref = "HEAD:" + source.relative_to(git_root).as_posix()
                data = subprocess.check_output(["git", "cat-file", "blob", ref], cwd=git_root)
                target = fixtures / source.relative_to(saved)
                target.parent.mkdir(exist_ok=True, parents=True)
                target.write_bytes(data)
        archive_replay = run_node("replay.mjs", fixtures)

        # Flask test client executes the route in process. No model download or network calls allowed.
        os.environ["HF_HUB_OFFLINE"] = "1"
        os.environ["TRANSFORMERS_OFFLINE"] = "1"
        original_connect = socket.socket.connect
        def offline_connect(*args, **kwargs):
            raise RuntimeError("Network disabled by offline audit.")
        socket.socket.connect = offline_connect
        sys.path.insert(0, str(frontend))
        try:
            import rag_knowledge_base
            import rag_api_server
            p = Path(tmp) / "public-fixture.json"
            sample = [{"text_chunk_to_embed": c["quote"], "metadata":{"comment_id": c["source_key"]}} for c in public["cards"]]
            p.write_text(json.dumps(sample, ensure_ascii=False), encoding="utf-8")
            rag = rag_knowledge_base.DroneCommentRAG(json_file_path=str(p))
            docs = rag.load_data()
            try:
                rag.setup_embedding_model()
                embedding_state = "initialized"
            except RuntimeError as e:
                embedding_state = str(e)
            client = rag_api_server.app.test_client()
            status = {k: (client.get(k) if k.endswith("status") else client.post(k, json={"query":"紧凑"})).status_code
                      for k in ("/api/status", "/api/initialize", "/api/context", "/api/query")}
            rag_result = {"fixture": "public 36 short cards adapted to historical JSON schema",
                          "loaded_documents": len(docs), "unique_comments": rag.stats["total_comments"],
                          "embedding_init": embedding_state, "api_statuses": status}
        except ImportError as e:
            rag_result = {"dependency_missing": str(e)}
        finally:
            sys.path.remove(str(frontend))
            socket.socket.connect = original_connect
    return {"node": subprocess.check_output(["node", "--version"], text=True).strip(), "verify": run_node("verify.mjs"),
            "worktree_replay": run_node("replay.mjs", saved), "git_blob_replay": archive_replay, "rag": rag_result}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("frontend", type=Path, help="PR75 prototypes/drone-configurator")
    parser.add_argument("--private-source", type=Path, help="Private local research corpus root (optional)")
    parser.add_argument("--runtimes", action="store_true", help="Check PR75 replay, historical Python loader and Flask endpoints")
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    target = args.frontend.resolve()
    public = read_json(target / "src/data/evidenceCards.json")
    result = {"commit": subprocess.check_output(["git", "rev-parse", "HEAD"], text=True, cwd=target).strip(),
              "public_source_csv_sha256": public["sha256"], "public": public_checks(public)}
    if args.private_source:
        result["private"] = private_checks(args.private_source, public)
    if args.runtimes:
        result["runtimes"] = runtime_checks(target, public)
    args.out.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
