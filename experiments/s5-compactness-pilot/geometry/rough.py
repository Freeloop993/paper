def to_image(pid):
    """拼图坐标换成 1024 原图坐标。"""
    for s in SHEETS:
        if pid in s:
            i = s.index(pid); ox, oy = (i % 2) * 768, (i // 2) * 768
            r = ROUGH[pid]; f = lambda x, o: round((x - o) / 0.75)
            out = {'hubs': [(f(x, ox), f(y, oy)) for x, y in r['hubs']], 'top': f(r['top'], oy), 'bottom': f(r['bottom'], oy)}
            for k in ('left', 'right'):
                if k in r: out[k] = f(r[k], ox)
            return out
    raise KeyError(pid)
