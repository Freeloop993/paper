def final(auto):
    """auto: mark.py 的 auto.json。返回 {图号: [(x, y), …]}。"""
    flat = [(p, i) for p in auto for i in range(len(auto[p]['hubs']))]
    seen = [q for sheet in PASS1 for q in sheet]
    assert len(flat) == len(seen), (len(flat), len(seen))
    out = {}
    for n, ((p, i), (sx, sy)) in enumerate(zip(flat, seen)):
        k = n % 28; cx, cy = (k % 7) * 320 + 160, (k // 7) * 338 + 178
        ax, ay = auto[p]['hubs'][i]['auto']; dx, dy = PASS2.get('%s-%d' % (p, i + 1), (0, 0))
        out.setdefault(p, []).append((round(ax + (sx - cx) / 4) + dx, round(ay + (sy - cy) / 4) + dy))
    return out
